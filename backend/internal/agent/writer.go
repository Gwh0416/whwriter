package agent

import (
	"fmt"
	"strings"
)

type WriterAgent struct{}

func NewWriterAgent() *WriterAgent {
	return &WriterAgent{}
}

func (a *WriterAgent) Name() string { return "writer" }

type WriterInput struct {
	Platform       string
	GenreName      string
	ChapterWordCount int
	ChapterNumber  int
	IsGoverned     bool
}

func (a *WriterAgent) BuildSystemPrompt(in WriterInput) string {
	var b strings.Builder

	b.WriteString(fmt.Sprintf("你是一位专业的%s网络小说作家。你为%s平台写作。\n\n", in.GenreName, in.Platform))

	if in.IsGoverned {
		b.WriteString(writerGovernedContract)
	}

	b.WriteString(writerChapterMemoContract)
	b.WriteString(fmt.Sprintf(writerLengthGuidance, in.ChapterWordCount, in.ChapterWordCount-500, in.ChapterWordCount+500, in.ChapterWordCount-1000, in.ChapterWordCount+1000))
	b.WriteString(writerCoreRules)
	b.WriteString(writerCraftCard)
	b.WriteString(writerCreativeConstitution)
	b.WriteString(writerImmersionPillars)

	if in.ChapterNumber <= 3 {
		b.WriteString(fmt.Sprintf(writerGoldenOpening, in.ChapterNumber))
	}

	b.WriteString(writerOutputFormat)

	return b.String()
}

func (a *WriterAgent) SystemPrompt() string {
	return writerCoreRules
}

